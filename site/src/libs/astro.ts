import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import mdx from '@astrojs/mdx'
import sitemap from '@astrojs/sitemap'
import { minify } from 'terser'
import type { AstroIntegration } from 'astro'
import { getConfig } from './config'
import { docsDirectory, getDocsFsPath, getDocsPublicFsPath, getDocsStaticFsPath, validateDocsPaths } from './path'

// A list of static file paths that will be aliased to a different path.
const staticFileAliases = {
  '/assets/img/favicons/apple-touch-icon.png': '/apple-touch-icon.png',
  '/assets/img/favicons/favicon.ico': '/favicon.ico'
}

// A list of static scripts (relative to the `static` folder) that also get a minified `.min.js` copy.
const staticScriptsToMinify = ['assets/js/color-modes.js']

// A list of pages that will be excluded from the sitemap.
const sitemapExcludes = ['/404', '/docs']

export function bootstrap(): AstroIntegration[] {
  const sitemapExcludedUrls = sitemapExcludes.map((url) => `${getConfig().baseURL}${url}/`)
  let outDir: URL | undefined

  return [
    {
      name: 'bootstrap-integration',
      hooks: {
        'astro:config:setup': ({ addWatchFile }) => {
          // Reload the config when the integration is modified.
          addWatchFile(path.join(getDocsFsPath(), 'src/libs/astro.ts'))
        },
        'astro:config:done': async ({ config }) => {
          outDir = config.outDir
          cleanPublicDirectory()
          copyBootstrap()
          copyStatic()
          aliasStatic()
          await minifyStaticScripts()
          copyPagefindIndex()
        },
        'astro:build:done': ({ dir }) => {
          validateDocsPaths(dir)
          tidyHtml(dir)
        }
      }
    },
    // https://github.com/withastro/astro/issues/6475
    mdx() as AstroIntegration,
    sitemap({
      filter: (page) => sitemapFilter(page, sitemapExcludedUrls, outDir)
    })
  ]
}

// Elements whose content is whitespace-sensitive. The tidy step does not change their content.
const preservedElementsRegex = /(<(pre|textarea|script|style)\b[\s\S]*?<\/\2>)/i

// Tidy every built HTML page. `compressHTML` is off, so Astro keeps the source indentation and blank lines.
// - Astro always emits an uppercase `<!DOCTYPE html>`, even when the layout uses lowercase. Rewrite it to lowercase.
// - Remove trailing whitespace, leading indentation, and blank lines outside whitespace-sensitive elements. Line breaks
//   stay, so the spacing between inline elements does not change.
function tidyHtml(dir: URL) {
  const dirPath = fileURLToPath(dir)
  const files = fs.readdirSync(dirPath, { recursive: true, encoding: 'utf8' }).filter((file) => file.endsWith('.html'))

  for (const file of files) {
    const filePath = path.join(dirPath, file)
    const html = fs.readFileSync(filePath, 'utf8')

    fs.writeFileSync(filePath, tidyHtmlContent(html))
  }
}

function tidyHtmlContent(html: string) {
  const tidied = html
    .split(preservedElementsRegex)
    .map((part, index) => {
      // `split()` with capture groups returns [text, element, tagName, text, element, tagName, ...].
      if (index % 3 === 1) {
        return part
      }

      if (index % 3 === 2) {
        return ''
      }

      return part
        .replace(/[ \t]+$/gm, '')
        .replace(/^[ \t]+/gm, '')
        .replace(/\n{2,}/g, '\n')
    })
    .join('')
    .trim()

  return `${tidied.replace(/^<!DOCTYPE html>/, '<!doctype html>')}\n`
}

function cleanPublicDirectory() {
  fs.rmSync(getDocsPublicFsPath(), { force: true, recursive: true })
}

// Copy the previously-generated Pagefind search index from `_site/pagefind/`
// into `site/public/pagefind/` so `astro dev` can serve it at `/pagefind/`.
// The index is regenerated by `npm run docs-build`; this step is a no-op if
// no build has been run yet, in which case dev simply has no search results.
function copyPagefindIndex() {
  const source = path.join(process.cwd(), '_site', 'pagefind')

  if (!fs.existsSync(source)) {
    return
  }

  const destination = path.join(getDocsPublicFsPath(), 'pagefind')

  fs.mkdirSync(destination, { recursive: true })
  fs.cpSync(source, destination, { recursive: true })
}

// Copy the `dist` folder from the root of the repo containing the latest version of Bootstrap to make it available from
// the `/dist` URL.
function copyBootstrap() {
  const source = path.join(process.cwd(), 'dist')
  const destination = path.join(getDocsPublicFsPath(), 'dist')

  fs.mkdirSync(destination, { recursive: true })
  fs.cpSync(source, destination, { recursive: true })
}

// Copy the content as-is of the `static` folder to make it available from the `/` URL.
// A folder named `[version]` will automatically be renamed to the current version of the docs extracted from the
// `config.yml` file.
function copyStatic() {
  const source = getDocsStaticFsPath()
  const destination = path.join(getDocsPublicFsPath())

  copyStaticRecursively(source, destination)
}

// Alias (copy) some static files to different paths.
function aliasStatic() {
  const source = getDocsStaticFsPath()
  const destination = path.join(getDocsPublicFsPath())

  for (const [aliasSource, aliasDestination] of Object.entries(staticFileAliases)) {
    fs.cpSync(path.join(source, aliasSource), path.join(destination, aliasDestination))
  }
}

// Write a minified `.min.js` copy of each static script next to the original. The pages load the minified copy, and
// the original stays readable for the docs code snippets and the examples download.
async function minifyStaticScripts() {
  for (const script of staticScriptsToMinify) {
    const source = path.join(getDocsPublicFsPath(), script)
    const { code } = await minify(fs.readFileSync(source, 'utf8'), {
      compress: { passes: 2 },
      mangle: true,
      format: { comments: /^!/ }
    })

    if (!code) {
      throw new Error(`Failed to minify "${script}".`)
    }

    fs.writeFileSync(source.replace(/\.js$/, '.min.js'), `${code}\n`)
  }
}

// See `copyStatic()` for more details.
function copyStaticRecursively(source: string, destination: string) {
  const entries = fs.readdirSync(source, { withFileTypes: true })

  for (const entry of entries) {
    if (entry.isFile()) {
      fs.cpSync(path.join(source, entry.name), replacePathVersionPlaceholder(path.join(destination, entry.name)))
    } else if (entry.isDirectory()) {
      fs.mkdirSync(replacePathVersionPlaceholder(path.join(destination, entry.name)), { recursive: true })

      copyStaticRecursively(path.join(source, entry.name), path.join(destination, entry.name))
    }
  }
}

function replacePathVersionPlaceholder(name: string) {
  return name.replace('[version]', getConfig().docs_version)
}

function sitemapFilter(page: string, excludedUrls: string[], outDir: URL | undefined) {
  if (excludedUrls.includes(page)) {
    return false
  }

  return !isNoindexPage(page, outDir)
}

// Alias pages redirect to their new URL and use `noindex`. Keep them out of the sitemap.
function isNoindexPage(page: string, outDir: URL | undefined) {
  if (!outDir) {
    return false
  }

  const htmlFile = new URL(`.${new URL(page).pathname}index.html`, outDir)

  if (!fs.existsSync(htmlFile)) {
    return false
  }

  return /<meta name="robots" content="noindex"/.test(fs.readFileSync(htmlFile, 'utf8'))
}
